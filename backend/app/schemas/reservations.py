"""Patient reservation API schemas.

Request bodies forbid unknown fields: a client cannot send a status, an actor,
a price, a timestamp, an organization or anything else the server decides; such
requests fail with 422 instead of being silently ignored.

Reservations are addressed by their reference (``RX-`` and 10 characters),
never by database id. Responses carry no user ids, stock adjustment ids or
transaction ids.
"""

import uuid
from datetime import datetime
from decimal import Decimal
from enum import StrEnum
from typing import Annotated, Literal

from pydantic import BaseModel, ConfigDict, Field, StringConstraints

from app.models.enums import AvailabilityStatus

REFERENCE_PATTERN = r"^[Rr][Xx]-[A-Za-z0-9]{10}$"
Reference = Annotated[str, StringConstraints(strip_whitespace=True, pattern=REFERENCE_PATTERN)]
Reason = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=500)]
OptionalReason = Annotated[str, StringConstraints(strip_whitespace=True, max_length=500)]
UnitLabel = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=60)]
PackSize = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=100)]


class Strict(BaseModel):
    model_config = ConfigDict(extra="forbid")


class ReservationStatusFilter(StrEnum):
    """The status as patients and pharmacies see it: a reservation past its
    deadline is ``expired`` even before the system records it."""

    REQUESTED = "requested"
    CONFIRMED = "confirmed"
    DECLINED = "declined"
    CANCELLED = "cancelled"
    COLLECTED = "collected"
    EXPIRED = "expired"


DispensingClass = Literal["unclassified", "non_prescription", "prescription_only"]
StockUnit = Literal["pack", "unit", "unknown"]


# ---------------------------------------------------------------------------
# Shared pieces
# ---------------------------------------------------------------------------
class UnitInfo(BaseModel):
    """How the medicine is counted. ``unit_version`` changes whenever the unit
    changes; a reservation or acknowledgement must quote the current one."""

    unit_version: int
    stock_unit: str
    unit_label: str | None
    pack_size: str | None


class MedicineSummary(BaseModel):
    product_id: int
    product_name: str
    drug_name: str
    brand: str | None
    strength: str | None
    dosage_form: str | None


class BranchSummary(BaseModel):
    location_id: int
    name: str
    pharmacy_name: str
    address: str | None
    city: str | None
    phone: str | None
    whatsapp_phone: str | None


class HistoryEntry(BaseModel):
    from_status: str | None
    to_status: str
    by: Literal["patient", "pharmacy", "system"]
    by_name: str | None = Field(default=None, description="Pharmacy views only: the staff member.")
    system_reason: str | None
    reason: str | None
    changed_at: datetime


# ---------------------------------------------------------------------------
# Patient
# ---------------------------------------------------------------------------
class ReservationCreate(Strict):
    location_id: int = Field(gt=0, description="The pharmacy branch.")
    product_id: int = Field(gt=0, description="The catalogue product.")
    quantity: int = Field(ge=1, le=1000, description="In the medicine's stock unit.")
    unit_version: int = Field(
        ge=1, description="The unit version the patient was shown (from GET /reservations/options)."
    )
    client_request_id: uuid.UUID = Field(
        description="Generated by the client once per request; retries with the same id return the "
        "same reservation instead of creating another."
    )
    contact_phone: str | None = Field(
        default=None,
        max_length=30,
        description="Number the pharmacy may call about this reservation. Defaults to the account's phone.",
    )
    note: OptionalReason | None = None


class ReservationCancel(Strict):
    reason: OptionalReason | None = None


class ReservationOptions(BaseModel):
    """Whether a medicine can be reserved at a branch, without stock figures."""

    reservable: bool
    reason: str | None = Field(description="Why not (a code), when ``reservable`` is false.")
    message: str | None
    availability_status: AvailabilityStatus | None = Field(
        description="The same status public search shows; never a quantity."
    )
    max_quantity: int | None
    unit: UnitInfo
    unit_price: Decimal | None
    currency: str | None
    response_hours: int = 24
    collection_hours: int = 24


class PatientReservation(BaseModel):
    reference: str
    status: ReservationStatusFilter
    medicine: MedicineSummary
    branch: BranchSummary
    quantity: int
    unit: UnitInfo
    unit_price: Decimal
    currency: str
    contact_phone: str = Field(description="The number the patient gave for this reservation.")
    note: str | None
    submitted_at: datetime
    respond_by: datetime = Field(description="The pharmacy must confirm or decline by then.")
    confirmed_at: datetime | None
    collect_by: datetime | None = Field(description="After confirmation: collect by then.")
    closed_at: datetime | None
    decline_reason: str | None
    cancel_reason: str | None
    system_reason: str | None
    can_cancel: bool


class PatientReservationDetail(PatientReservation):
    history: list[HistoryEntry]


# ---------------------------------------------------------------------------
# Pharmacy
# ---------------------------------------------------------------------------
class PatientContact(BaseModel):
    name: str
    phone: str | None = Field(
        description="Shown to members of the handling pharmacy while the reservation is open; "
        "null once it is closed."
    )


class StockAllocation(BaseModel):
    """The branch's stock for this medicine against open reservations."""

    recorded_quantity: int | None = Field(description="Stock on record (null: no stock record).")
    allocated_quantity: int = Field(description="Held by open requests and confirmed reservations.")
    available_to_reserve: int = Field(description="Unallocated: recorded minus held (never negative).")
    min_stock: int = Field(description="Kept back from new reservations at this branch.")
    reservable_quantity: int = Field(description="What new requests may still take: unallocated minus min_stock.")
    shortfall: int = Field(description="Held beyond the recorded stock (after a stock correction).")
    last_updated: datetime | None
    this_reservation_at_risk: bool


class CollectionDetail(BaseModel):
    collected_at: datetime
    collected_by_name: str | None
    quantity: int
    recorded_quantity_before: int
    quantity_after: int
    override: bool
    override_by_name: str | None
    verified_on_hand: int | None
    recorded_quantity_seen: int | None
    override_reason: str | None


class PharmacyReservation(BaseModel):
    reference: str
    status: ReservationStatusFilter
    medicine: MedicineSummary
    location_id: int
    location_name: str
    quantity: int
    unit: UnitInfo
    unit_price: Decimal
    currency: str
    patient: PatientContact
    note: str | None
    submitted_at: datetime
    respond_by: datetime = Field(description="Response deadline: confirm or decline by then.")
    confirmed_at: datetime | None
    collect_by: datetime | None = Field(description="Collection deadline (set on confirmation).")
    closed_at: datetime | None
    decline_reason: str | None
    cancel_reason: str | None
    system_reason: str | None
    actions: list[Literal["confirm", "decline", "cancel", "collect", "override"]] = Field(
        description="What the caller's role may do now."
    )


class PharmacyReservationDetail(PharmacyReservation):
    history: list[HistoryEntry]
    stock: StockAllocation
    collection: CollectionDetail | None


class ReservationDecision(Strict):
    reason: Reason


class CollectionOverrideRequest(Strict):
    verified_on_hand: int = Field(ge=0, le=2_000_000_000, description="The physical count.")
    recorded_quantity_seen: int = Field(
        ge=0, le=2_000_000_000, description="The recorded quantity shown when counting."
    )
    reason: Annotated[str, StringConstraints(strip_whitespace=True, min_length=10, max_length=500)]
    physically_verified: Literal[True] = Field(description="Must be true: the stock was counted.")


class CollectRequest(Strict):
    reference: Reference = Field(
        description="The reference the patient shows, typed by the staff member. It must match the "
        "reservation (case-insensitive); otherwise 422 reference_mismatch and nothing is collected."
    )
    override: CollectionOverrideRequest | None = Field(
        default=None, description="Owners and managers only, when the recorded stock is too low."
    )


# ---------------------------------------------------------------------------
# Product settings (platform admins) and branch acknowledgement
# ---------------------------------------------------------------------------
class SettingsProblem(BaseModel):
    code: str
    message: str


class ReservationSettings(UnitInfo):
    product_id: int
    is_active: bool
    dispensing_class: str
    max_reservation_quantity: int | None = Field(description="This medicine's own limit per reservation, if any.")
    effective_max_quantity: int = Field(description="The limit that applies (its own, else the default).")
    ready: bool = Field(description="The catalogue settings allow reservations; each branch then decides by stock.")
    problems: list[SettingsProblem] = Field(description="Why this medicine cannot be reserved anywhere yet.")


class ReservationSettingsUpdate(Strict):
    dispensing_class: DispensingClass | None = None
    stock_unit: StockUnit | None = None
    unit_label: UnitLabel | None = None
    pack_size: PackSize | None = None
    max_reservation_quantity: int | None = Field(default=None, ge=1, le=1000)


class ReservationSettingsHistory(BaseModel):
    dispensing_class: str
    stock_unit: str
    unit_label: str | None
    pack_size: str | None
    unit_version: int
    max_reservation_quantity: int | None
    reservation_enabled: bool
    changed_by_name: str | None
    changed_at: datetime


class BranchMedicine(BaseModel):
    """One medicine a pharmacy branch has a stock record for, as reservations see it."""

    product_id: int
    product_name: str
    unit: UnitInfo
    dispensing_class: str
    listed: bool = Field(description="The branch lists it (price published).")
    recorded_quantity: int
    held_quantity: int = Field(description="Held by open requests and confirmed reservations.")
    unallocated_quantity: int
    min_stock: int
    reservable_quantity: int
    max_quantity: int = Field(description="The most one reservation may ask for.")
    reservable: bool
    reason: str | None = Field(description="Why it cannot be reserved here now, if not.")
    message: str | None
